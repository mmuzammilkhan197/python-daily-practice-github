a = 20
b = 10

# Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)
print("Power:", a ** 2)

# Comparison Operators
print("Equal:", a == b)
print("Not Equal:", a != b)
print("Greater:", a > b)
print("Less:", a < b)

# Logical Operators
print("AND:", a > 10 and b < 20)
print("OR:", a < 10 or b == 10)
print("NOT:", not(a > b))